import { Alert, Button, MenuItem, Stack, TextField, Typography } from "@mui/material";
import { useEffect, useState } from "react";
import { useParams } from "react-router-dom";
import { api } from "../api/client";
import { TEST_TYPES, type TestCase } from "../types";

export function TestCaseDetailPage() {
  const { caseId = "" } = useParams();
  const [item, setItem] = useState<TestCase | null>(null);
  const [error, setError] = useState("");
  const [saved, setSaved] = useState("");
  const [dataText, setDataText] = useState("{}");

  useEffect(() => {
    void api<TestCase>(`/api/test-cases/${caseId}`)
      .then((row) => {
        setItem(row);
        setDataText(JSON.stringify(row.test_data || {}, null, 2));
      })
      .catch((err: Error) => setError(err.message));
  }, [caseId]);

  async function save() {
    if (!item) return;
    setError("");
    setSaved("");
    let testData: Record<string, string>;
    try {
      const parsed = JSON.parse(dataText) as unknown;
      if (!parsed || typeof parsed !== "object" || Array.isArray(parsed)) {
        setError("Test data must be a JSON object.");
        return;
      }
      testData = Object.fromEntries(Object.entries(parsed).map(([key, value]) => [key, String(value)]));
    } catch {
      setError("Test data is not valid JSON.");
      return;
    }
    try {
      const updated = await api<TestCase>(`/api/test-cases/${item.id}`, {
        method: "PATCH",
        body: JSON.stringify({
          title: item.title,
          description: item.description,
          requirement_ref: item.requirement_ref,
          preconditions: item.preconditions,
          steps: item.steps,
          expected_result: item.expected_result,
          test_type: item.test_type,
          priority: item.priority,
          risk_level: item.risk_level,
          automation_suitability: item.automation_suitability,
          tags: item.tags,
          status: item.status,
          test_data: testData,
        }),
      });
      setItem(updated);
      setSaved("Saved.");
    } catch (err) {
      setError(err instanceof Error ? err.message : "Save failed");
    }
  }

  if (error && !item) return <Alert severity="error">{error}</Alert>;
  if (!item) return <Typography>Loading test case…</Typography>;
  const metadata = item.generation_metadata || {};
  return (
    <Stack spacing={2}>
      <Typography variant="h4">{item.case_key}</Typography>
      {metadata.provider === "mock" && (
        <Alert severity="info">
          Generated by the deterministic mock provider ({metadata.model}). This case was not produced by an external language model.
          Token counts, when present, are estimates.
        </Alert>
      )}
      {metadata.produced_by_external_model && (
        <Alert severity="warning">
          Provider {metadata.provider} / {metadata.model}. Token source: {metadata.token_usage?.source || "not reported"}.
        </Alert>
      )}
      {error && <Alert severity="error">{error}</Alert>}
      {saved && <Alert severity="success">{saved}</Alert>}
      <TextField label="Title" value={item.title} onChange={(event) => setItem({ ...item, title: event.target.value })} />
      <TextField
        label="Description"
        value={item.description}
        multiline
        minRows={2}
        onChange={(event) => setItem({ ...item, description: event.target.value })}
      />
      <TextField
        label="Requirement reference"
        value={item.requirement_ref}
        onChange={(event) => setItem({ ...item, requirement_ref: event.target.value })}
      />
      <TextField
        label="Preconditions (one per line)"
        value={item.preconditions.join("\n")}
        multiline
        minRows={3}
        onChange={(event) => setItem({ ...item, preconditions: event.target.value.split("\n").filter(Boolean) })}
      />
      <TextField
        label="Test steps (one per line)"
        value={item.steps.join("\n")}
        multiline
        minRows={4}
        onChange={(event) => setItem({ ...item, steps: event.target.value.split("\n").filter(Boolean) })}
      />
      <TextField label="Test data JSON" value={dataText} multiline minRows={4} onChange={(event) => setDataText(event.target.value)} />
      <TextField
        label="Expected result"
        value={item.expected_result}
        multiline
        minRows={2}
        onChange={(event) => setItem({ ...item, expected_result: event.target.value })}
      />
      <Stack direction={{ xs: "column", md: "row" }} spacing={1}>
        <TextField select label="Type" value={item.test_type} onChange={(event) => setItem({ ...item, test_type: event.target.value })} fullWidth>
          {TEST_TYPES.map((type) => (
            <MenuItem key={type} value={type}>{type}</MenuItem>
          ))}
        </TextField>
        <TextField select label="Priority" value={item.priority} onChange={(event) => setItem({ ...item, priority: event.target.value })} fullWidth>
          {["critical", "high", "medium", "low"].map((value) => (
            <MenuItem key={value} value={value}>{value}</MenuItem>
          ))}
        </TextField>
        <TextField select label="Risk" value={item.risk_level} onChange={(event) => setItem({ ...item, risk_level: event.target.value })} fullWidth>
          {["critical", "high", "medium", "low"].map((value) => (
            <MenuItem key={value} value={value}>{value}</MenuItem>
          ))}
        </TextField>
        <TextField
          select
          label="Automation"
          value={item.automation_suitability}
          onChange={(event) => setItem({ ...item, automation_suitability: event.target.value })}
          fullWidth
        >
          {["high", "medium", "low", "manual_only"].map((value) => (
            <MenuItem key={value} value={value}>{value}</MenuItem>
          ))}
        </TextField>
        <TextField select label="Status" value={item.status} onChange={(event) => setItem({ ...item, status: event.target.value })} fullWidth>
          {["draft", "reviewed", "approved"].map((value) => (
            <MenuItem key={value} value={value}>{value}</MenuItem>
          ))}
        </TextField>
      </Stack>
      <TextField
        label="Tags, comma separated"
        value={item.tags.join(", ")}
        onChange={(event) =>
          setItem({
            ...item,
            tags: event.target.value.split(",").map((tag) => tag.trim()).filter(Boolean),
          })
        }
      />
      <Button variant="contained" onClick={() => void save()}>
        Save changes
      </Button>
    </Stack>
  );
}
